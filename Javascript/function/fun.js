// parameters are variables that are passed into a function to provide input values. parameters are listed in the function definition and can be used within the function body to perform operations or calculations.

function add(x, y) {
    return x + y;
}
console.log(add(5, 10));

// return keyword is used to specify the code that a function execute and return value.


function tocelcius(fahrenheit) {
    return (fahrenheit - 32) * 5 / 9;
}
console.log(tocelcius(100)); 

