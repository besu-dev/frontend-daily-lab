//   // javascript has several assignment operators, including +=, -=, *=, /=, and %=, which can be used to perform arithmetic operations and assign the result to a variable.
let x = 10;
// assign value of 10 to variable x
x += 5; // is equal to x = x + 5, so x is now 15

console.log(x); // Output: 15

// javascript operators are used to perform operations on variables and values. There are several types of operators in javascript, including arithmetic, comparison, logical, and assignment operators.

//  arithmetic operators are used to perform mathematical operations on numbers.

let a = 10;
let b = 5;

console.log(a + b);
console.log(a * b);
console.log(a % b);
console.log(a ** b); // exponentiation operator, raises a to the power of b
console.log(a++); // increment operator, increases the value of a by 1

// comparison operators are used to compare two values and return a boolean value (true or false).

let c = 10;
let d = 5;
let h = "10";
console.log(c > d);
console.log(c >= d);
console.log(c == d);
console.log(c != d);
console.log(c == h); // strict equality operator
console.log(c === h); // loose equality operator
// logical operators are used to combine multiple boolean expressions and return a boolean value.

let e = true;
let f = false;

console.log(e && f);
console.log(e || f);
console.log(!e);
